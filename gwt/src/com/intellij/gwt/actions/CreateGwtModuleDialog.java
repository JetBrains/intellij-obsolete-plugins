  private @NlsSafe String computeHtmlDirectoryInSourcesPath() {
    final List<String> names = StringUtil.split(myGwtModuleNameField.getText(), ".");
    final PsiDirectory directory = names.size() > 1 ? CreateGwtModuleAction.getRootDirectory(mySourceDirectory) : mySourceDirectory;
    final StringBuilder path = new StringBuilder(directory.getVirtualFile().getPath());
    for (int i = 0; i < names.size() - 1; i++) {
      String name = names.get(i);
      if (!name.isEmpty()) {
        if (!path.isEmpty() && path.charAt(path.length() - 1) != '/') {
          path.append('/');
        }
        path.append(StringUtil.decapitalize(name));
      }
    }
    path.append("/").append(GwtModuleXmlConstants.DEFAULT_PUBLIC_PATH);
    return FileUtil.toSystemDependentName(path.toString());
  }

