  private void adjustDirectory() {
    if (myDirectoryWasChangedByHand) return;
    myAdjustingDirectory = true;
    try {
      final int lastItemIndex = myComboBox.getItemCount() - 1;
      boolean isLastItemSelected = myComboBox.getSelectedItem().equals(myComboBox.getItemAt(lastItemIndex));
      final String newPath = computeHtmlDirectoryInSourcesPath();
      if (isLastItemSelected) {
        myComboBox.getEditor().setItem(newPath);
      }
      myComboBox.removeItemAt(lastItemIndex);
      myComboBox.addItem(newPath);
    }
    finally {
      myAdjustingDirectory = false;
    }
  }

